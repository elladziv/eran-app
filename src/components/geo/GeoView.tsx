// Map viewBox shows the Levant/Middle East region of the design
const MAP_VIEWBOX = '200 100 680 700'

export function GeoView() {
  const selectedCountry  = useAppStore((s) => s.selectedCountry)
  const selectCountry    = useAppStore((s) => s.selectCountry)
  const orchestraSlots = useAppStore((s) => s.orchestraSlots)

  const countriesWithVideos = new Set(VIDEO_FILES.map((v) => v.country))

  const handleCountryClick = (country: Country) => {
    selectCountry(selectedCountry === country ? null : country)
  }

  return (
    <div className="w-full h-full flex items-center justify-center overflow-hidden">
      <svg
        viewBox={MAP_VIEWBOX}
        preserveAspectRatio="xMidYMid meet"
        className="w-full h-full"
        style={{ display: 'block' }}
      >
        {/* Ocean / background */}
        <rect
          x="0"
          y="0"
          width="1366.75"
          height="962.24"
          fill="var(--color-surface-inner)"
        />

        {/* Country shapes */}
        {Object.entries(COUNTRY_PATHS).map(([key, { country, d }]) => {
          const isSelected = selectedCountry === country
          const hasVideos = countriesWithVideos.has(country)
          const inOrchestra = orchestraSlots.some((s) => s.video.country === country)

          return (
            <g key={key}>
              <path
                d={d}
                fill={
                  isSelected
                    ? 'var(--color-accent-brown)'
                    : hasVideos
                      ? 'var(--color-category-chorus-play)'
                      : 'var(--color-bg-pattern-dot)'
                }
                stroke="var(--color-surface-inner)"
                strokeWidth={1.5}
                opacity={isSelected ? 1 : 0.8}
                style={{ cursor: 'pointer', transition: 'fill 0.2s ease' }}
                onClick={() => handleCountryClick(country)}
              />
              {hasVideos && (
                <circle
                  cx={COUNTRY_LABEL_POS[country]?.x ?? 0}
                  cy={(COUNTRY_LABEL_POS[country]?.y ?? 0) - 16}
                  r={8}
                  fill={inOrchestra ? 'var(--color-accent-gold)' : 'var(--color-accent-brown)'}
                  pointerEvents="none"
                />
              )}
            </g>
          )
        })}

        {/* Country name labels */}
        {Object.entries(COUNTRY_PATHS).map(([key, { country }]) => {
          const pos = COUNTRY_LABEL_POS[country]
          if (!pos) return null
          const isSelected = selectedCountry === country
          return (
            <text
              key={`label-${key}`}
              x={pos.x}
              y={pos.y}
              textAnchor="middle"
              dominantBaseline="middle"
              fontSize={11}
              fontWeight={isSelected ? '700' : '500'}
              fill={isSelected ? 'var(--color-surface-inner)' : 'var(--color-text-primary)'}
              pointerEvents="none"
              style={{ fontFamily: 'Urbani, sans-serif' }}
            >
              {COUNTRY_LABELS[country]}
            </text>
          )
        })}
      </svg>
    </div>
  )
}
